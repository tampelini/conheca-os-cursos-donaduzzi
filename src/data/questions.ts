import type { CategoryId, OptionId, Question } from '../types';

const LETTERS = ['a', 'b', 'c', 'd'] as const;

/**
 * Marcador usado nas perguntas pendentes: enquanto o texto de alguma alternativa
 * contiver este marcador, a pergunta não pode ser ativada nem sorteada.
 */
export const PLACEHOLDER = 'PREENCHER';

export function hasPlaceholder(q: Pick<Question, 'prompt' | 'options' | 'explanation'>): boolean {
  return [q.prompt, q.explanation, ...q.options.map((o) => o.text)].some((t) => t.includes(PLACEHOLDER));
}

function q(
  id: string,
  category: CategoryId,
  prompt: string,
  options: [string, string, string, string],
  correct: (typeof LETTERS)[number],
  explanation: string,
): Question {
  return {
    id,
    category,
    prompt,
    options: options.map((text, i) => ({ id: LETTERS[i] as OptionId, text })),
    correctOptionId: correct,
    explanation,
    active: true,
  };
}

/** Pergunta com dado ainda não confirmado: nasce inativa e sinalizada no painel. */
function pending(...args: Parameters<typeof q>): Question {
  return { ...q(...args), active: false, pending: true };
}

